#!/usr/bin/env python3
"""Generate source/generated/Strings.mc from the six strings.xml resource files.

Connect IQ picks a compiled string resource by the system locale and cannot
switch it at runtime. To support an in-app language switcher we emit a plain
Monkey C table keyed by language code so the app can look translations up (and
change them) at runtime. Only the base "eng" strings.xml is guaranteed to be a
superset; all six are kept in sync by CI, so we read keys per language.

Run: python3 scripts/generate_strings.py
"""

import os
import xml.etree.ElementTree as ET

# Language code -> resource folder. "eng" is the base (default) resource dir.
LANGUAGES = [
    ("eng", "resources"),
    ("por", "resources-por"),
    ("spa", "resources-spa"),
    ("fre", "resources-fre"),
    ("deu", "resources-deu"),
    ("ita", "resources-ita"),
]

# Native language names shown in the in-app language menu.
NATIVE_NAMES = {
    "eng": "English",
    "por": "Português",
    "spa": "Español",
    "fre": "Français",
    "deu": "Deutsch",
    "ita": "Italiano",
}

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT_PATH = os.path.join(REPO_ROOT, "source", "generated", "Strings.mc")


def read_strings(folder):
    """Return an ordered {id: value} dict from a folder's strings.xml.

    ElementTree unescapes XML entities (&amp; -> &, etc.) for us.
    """
    path = os.path.join(REPO_ROOT, folder, "strings", "strings.xml")
    tree = ET.parse(path)
    root = tree.getroot()
    result = {}
    for node in root.findall("string"):
        key = node.get("id")
        value = node.text if node.text is not None else ""
        result[key] = value
    return result


def mc_string_literal(value):
    """Escape a Python string into a Monkey C double-quoted string literal."""
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return '"' + escaped + '"'


def emit_dictionary(entries, indent):
    """Emit a Monkey C dictionary literal body from an ordered {key: value}."""
    pad = " " * indent
    lines = []
    for key, value in entries.items():
        lines.append(
            "%s%s => %s"
            % (pad, mc_string_literal(key), mc_string_literal(value))
        )
    return ",\n".join(lines)


BASE_CODE = "eng"
LANGUAGE_INDENT = 16
BASE_INDENT = 12

HEADER_LINES = [
    "// AUTO-GENERATED by scripts/generate_strings.py. DO NOT EDIT.",
    "//",
    "// Runtime i18n table. Connect IQ selects compiled string",
    "// resources by system locale and cannot switch them at runtime,",
    "// so translations live here and are chosen by language code.",
    "import Toybox.Lang;",
    "",
    "module I18n {",
]

TABLE_OPENING_LINES = [
    "",
    "    // Returns the {key=>value} dictionary for ONE code so only the",
    "    // chosen language is allocated. The default branch returns eng.",
    "    function table(code as Lang.String) as Lang.Dictionary {",
]


def language_codes():
    return [code for code, _ in LANGUAGES]


def constant_lines(codes):
    codes_literal = ", ".join('"%s"' % c for c in codes)
    names_pairs = ", ".join(
        '"%s"=>%s' % (c, mc_string_literal(NATIVE_NAMES[c])) for c in codes
    )
    return [
        "    const CODES = [%s];" % codes_literal,
        "    const NAMES = { %s };" % names_pairs,
    ]


def translated_entries(tables, code, base_order):
    """Every base key, falling back to the eng value when a translation lacks it."""
    return {key: tables[code].get(key, tables[BASE_CODE][key]) for key in base_order}


def language_branch_lines(code, entries):
    return [
        '        if (code.equals("%s")) {' % code,
        "            return {",
        emit_dictionary(entries, LANGUAGE_INDENT),
        "            };",
        "        }",
    ]


def base_branch_lines(tables, base_order):
    """eng is the default fallthrough of table()."""
    entries = {key: tables[BASE_CODE][key] for key in base_order}
    return [
        "        return {",
        emit_dictionary(entries, BASE_INDENT),
        "        };",
        "    }",
        "}",
        "",
    ]


def table_lines(tables, base_order):
    lines = list(TABLE_OPENING_LINES)
    for code in language_codes():
        if code != BASE_CODE:
            lines += language_branch_lines(code, translated_entries(tables, code, base_order))
    return lines + base_branch_lines(tables, base_order)


def render_module(tables):
    """Key order follows the base (eng) file."""
    base_order = list(tables[BASE_CODE].keys())
    return "\n".join(HEADER_LINES + constant_lines(language_codes()) + table_lines(tables, base_order))


def write_output(text):
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(text)


def main():
    tables = {code: read_strings(folder) for code, folder in LANGUAGES}
    write_output(render_module(tables))
    print(
        "Generated %s: %d languages, %d keys each"
        % (
            os.path.relpath(OUTPUT_PATH, REPO_ROOT),
            len(LANGUAGES),
            len(tables[BASE_CODE]),
        )
    )


if __name__ == "__main__":
    main()
